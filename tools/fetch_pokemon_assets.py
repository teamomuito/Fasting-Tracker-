#!/usr/bin/env python3
"""Regenerates the Pokémon species list and PC sprites used by the favorite picker.

Sources (all from PokeAPI, over raw.githubusercontent.com):
  - https://github.com/PokeAPI/pokeapi  data/v2/csv  species names and language ids
  - https://github.com/PokeAPI/sprites  Generation VIII PC icons for Pokédex 1-898, and
                                        front sprites for 899-1025, which have no PC icon.

Writes:
  - app/src/main/java/app/fasting/domain/AllPokemon.kt
  - app/src/main/assets/pokemon/pc/<dex>.png

Run from the repository root:  python3 tools/fetch_pokemon_assets.py
Sprites and Pokémon names are Nintendo, Game Freak and Creatures property. See README before redistributing.
"""

import csv
import io
import shutil
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

DATA = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv"
SPRITES = "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon"
LAST_DEX = 1025
PC_ICON_LAST_DEX = 898

ROOT = Path(__file__).resolve().parent.parent
KOTLIN_OUT = ROOT / "app/src/main/java/app/fasting/domain/AllPokemon.kt"
ASSET_DIR = ROOT / "app/src/main/assets/pokemon/pc"


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def english_names() -> dict[int, str]:
    languages = csv.DictReader(io.StringIO(fetch(f"{DATA}/languages.csv").decode("utf-8")))
    english_id = next(row["id"] for row in languages if row["iso639"] == "en" and row["iso3166"] == "us")
    names = {}
    for row in csv.DictReader(io.StringIO(fetch(f"{DATA}/pokemon_species_names.csv").decode("utf-8"))):
        if row["local_language_id"] == english_id:
            names[int(row["pokemon_species_id"])] = row["name"]
    missing = [dex for dex in range(1, LAST_DEX + 1) if dex not in names]
    if missing:
        sys.exit(f"No English name for Pokédex numbers {missing[:10]}")
    return names


def kotlin_string_literal(text: str) -> str:
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    return f'"{escaped}"'


def write_kotlin(names: dict[int, str]) -> None:
    for name in names.values():
        if "|" in name:
            sys.exit(f"Name contains the list delimiter: {name}")
    joined = "|".join(names[dex] for dex in range(1, LAST_DEX + 1))
    KOTLIN_OUT.parent.mkdir(parents=True, exist_ok=True)
    KOTLIN_OUT.write_text(
        "// Generated by tools/fetch_pokemon_assets.py from PokeAPI data. Do not edit by hand.\n"
        "package app.fasting.domain\n"
        "\n"
        "/** One Pokémon species: its National Pokédex number and English name. */\n"
        "data class Pokemon(val dex: Int, val name: String)\n"
        "\n"
        "/** Names in Pokédex order, separated by '|'. Keeping them in one string keeps the class initializer small. */\n"
        f"private const val NAMES = {kotlin_string_literal(joined)}\n"
        "\n"
        "/** Every species in the National Pokédex, 1 to 1025, in order. */\n"
        "val ALL_POKEMON: List<Pokemon> = NAMES.split('|').mapIndexed { index, name -> Pokemon(index + 1, name) }\n",
        encoding="utf-8",
    )


def download_sprite(dex: int) -> str:
    target = ASSET_DIR / f"{dex}.png"
    if dex <= PC_ICON_LAST_DEX:
        # Every number up to 898 has a PC icon. A failed download here is an error, not a cue to use a front sprite.
        target.write_bytes(fetch(f"{SPRITES}/versions/generation-viii/icons/{dex}.png"))
        return "icon"
    target.write_bytes(fetch(f"{SPRITES}/{dex}.png"))
    return "front"


def write_sprites() -> None:
    if ASSET_DIR.exists():
        shutil.rmtree(ASSET_DIR)
    ASSET_DIR.mkdir(parents=True)
    with ThreadPoolExecutor(max_workers=8) as pool:
        kinds = list(pool.map(download_sprite, range(1, LAST_DEX + 1)))
    print(f"sprites: {kinds.count('icon')} PC icons, {kinds.count('front')} front sprites")


def main() -> None:
    names = english_names()
    write_kotlin(names)
    print(f"wrote {KOTLIN_OUT.relative_to(ROOT)} with {len(names)} species")
    write_sprites()
    print(f"wrote sprites to {ASSET_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
